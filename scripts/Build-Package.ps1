[CmdletBinding()]
param(
    [ValidatePattern('^[0-9]+\.[0-9]+\.[0-9]+$')]
    [string]$Version = '0.2.0',
    [switch]$SkipProviderBuild
)
# Builds and packages only. Never runs the installer, installs a toolchain,
# changes associations, or reads a user's ZBrush models/application assets.
$ErrorActionPreference = 'Stop'
$projectRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$provider = Join-Path $projectRoot 'build\provider\ZBrushThumbnailProvider.dll'
$manager = Join-Path $projectRoot 'build\installer\ZBrushThumbnailInstaller.exe'

function Get-BoundedSha256([string]$Path) {
    $stream = [System.IO.File]::Open($Path,[System.IO.FileMode]::Open,[System.IO.FileAccess]::Read,[System.IO.FileShare]::Read)
    $hash = $null
    try {
        if ($stream.Length -le 0 -or $stream.Length -gt 8MB) { throw 'Release input exceeds the bounded 8 MiB hash limit.' }
        $hash = [System.Security.Cryptography.SHA256]::Create()
        return [System.BitConverter]::ToString($hash.ComputeHash($stream)).Replace('-', '')
    } finally {
        if ($null -ne $hash) { $hash.Dispose() }
        $stream.Dispose()
    }
}

if (-not $SkipProviderBuild) {
    & (Join-Path $PSScriptRoot 'Build-Provider.cmd')
    if ($LASTEXITCODE -ne 0) { throw 'Provider compilation failed.' }
    & (Join-Path $projectRoot 'build\tests\ProviderTests.exe') $provider
    if ($LASTEXITCODE -ne 0) { throw 'Registration-free synthetic provider tests failed.' }
}
if (-not [System.IO.File]::Exists($provider)) { throw 'Built provider is absent.' }
$providerHash = Get-BoundedSha256 $provider
# Every clean local build stamps its newly built provider, rather than relying
# on a hash from somebody else's compiler. Never replace a deployed version.
$contract = @"
#pragma once
// Generated by scripts/Build-Package.ps1 from the local provider build.
namespace r8package {
inline constexpr wchar_t kProviderFilename[] = L"ZBrushThumbnailProvider.dll";
inline constexpr wchar_t kProviderSha256[] = L"$providerHash";
inline constexpr wchar_t kProviderClsid[] = L"{21728745-371F-4D3A-A7A0-54813A14A3B5}";
inline constexpr wchar_t kVersion[] = L"$Version";
inline constexpr wchar_t kManagerFilename[] = L"ZBrushThumbnailInstaller.exe";
}
"@
$utf8 = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText((Join-Path $projectRoot 'src\Package.h'),$contract,$utf8)
& (Join-Path $PSScriptRoot 'Build-Installer.cmd')
if ($LASTEXITCODE -ne 0) { throw 'Installer compilation failed.' }
$managerHash = Get-BoundedSha256 $manager

$releaseName = 'ZBrush-Explorer-Thumbnails-' + $Version + '-win-x64'
$dist = Join-Path $projectRoot 'dist'
$stage = Join-Path $dist $releaseName
$archive = Join-Path $dist ($releaseName + '.zip')
if ([System.IO.Directory]::Exists($stage) -or [System.IO.File]::Exists($archive)) {
    throw 'This release output already exists. Preserve it and use a new version or a clean build checkout.'
}
$documents = @('README.md','LICENSE','THIRD_PARTY_NOTICES.txt','docs\README.ko.md','docs\TESTING.md','docs\assets\synthetic-preview.png')
foreach ($document in $documents) {
    if (-not [System.IO.File]::Exists((Join-Path $projectRoot $document))) { throw ('Required release document is absent: ' + $document) }
}
[System.IO.Directory]::CreateDirectory($stage) | Out-Null
[System.IO.Directory]::CreateDirectory((Join-Path $stage 'docs')) | Out-Null
[System.IO.File]::Copy($manager,(Join-Path $stage 'ZBrushThumbnailInstaller.exe'),$false)
[System.IO.File]::Copy($provider,(Join-Path $stage 'ZBrushThumbnailProvider.dll'),$false)
foreach ($document in $documents) {
    $documentTarget = Join-Path $stage $document
    [System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($documentTarget)) | Out-Null
    [System.IO.File]::Copy((Join-Path $projectRoot $document),$documentTarget,$false)
}
$payloadSums = $managerHash + '  ZBrushThumbnailInstaller.exe' + "`n" + $providerHash + '  ZBrushThumbnailProvider.dll' + "`n"
[System.IO.File]::WriteAllText((Join-Path $stage 'SHA256SUMS.txt'),$payloadSums,$utf8)
Add-Type -AssemblyName System.IO.Compression.FileSystem
[System.IO.Compression.ZipFile]::CreateFromDirectory($stage,$archive,[System.IO.Compression.CompressionLevel]::Optimal,$false)
$archiveHash = Get-BoundedSha256 $archive
[System.IO.File]::WriteAllText((Join-Path $dist 'SHA256SUMS.txt'),$archiveHash + '  ' + $releaseName + '.zip' + "`n",$utf8)
Write-Output ('Archive=' + $archive)
Write-Output ('ArchiveSHA256=' + $archiveHash)
Write-Output ('InstallerSHA256=' + $managerHash)
Write-Output ('ProviderSHA256=' + $providerHash)
Write-Output 'Built and packaged only. The installer was not executed and no associations were changed.'
